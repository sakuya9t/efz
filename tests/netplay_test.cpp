static unsigned Hash31(const std::string& s)
{
    unsigned h = 0;
    for (unsigned char c : s)
        h = h * 31 + c;
    return h;
}

static void TestInflate()
{
    std::string out;
    CHECK(net::Inflate(kInputZ, sizeof(kInputZ), &out, 0x10000));
    net::Reader m;
    CHECK(m.Parse((const unsigned char*)out.data(), out.size()));
    CHECK(m.U32(1, 9) == 0);
    CHECK(m.I32(2) == -1);
    CHECK(m.U32(3) == 1234);
    std::vector<std::string> inputs = m.RepeatedBytes(5);
    CHECK(inputs.size() == 30);
    for (size_t i = 0; i < inputs.size() && i < 30; i++)
        CHECK(inputs[i].size() == 2 && (unsigned char)inputs[i][0] == kInputs[2 * i] &&
              (unsigned char)inputs[i][1] == kInputs[2 * i + 1]);

    // As a datagram: byte 0 says compressed, byte 1 is the type.
    std::string packet = std::string("\x01\x01", 2) + std::string((const char*)kInputZ, sizeof(kInputZ));
    int type = -1;
    std::string body;
    CHECK(net::Unpack((const unsigned char*)packet.data(), packet.size(), &type, &body));
    CHECK(type == net::kInput && body == out);

    CHECK(net::Inflate(kTextZ, sizeof(kTextZ), &out, 0x10000));
    CHECK(out.size() == 1648 && Hash31(out) == 2303845776u);
    CHECK(net::Inflate(kDynamicZ, sizeof(kDynamicZ), &out, 0x10000));
    CHECK(out.size() == 700 && Hash31(out) == 3205914357u);
    CHECK(net::Inflate(kStoredZ, sizeof(kStoredZ), &out, 0x10000));
    CHECK(out == "stored!");

    // Damaged: a wrong Adler-32, cut short, a bad header, more than allowed.
    unsigned char bad[sizeof(kTextZ)];
    memcpy(bad, kTextZ, sizeof(bad));
    bad[sizeof(bad) - 1] ^= 1;
    CHECK(!net::Inflate(bad, sizeof(bad), &out, 0x10000));
    CHECK(!net::Inflate(kTextZ, sizeof(kTextZ) / 2, &out, 0x10000));
    bad[0] = 0x79;
    CHECK(!net::Inflate(bad, sizeof(bad), &out, 0x10000));
    CHECK(!net::Inflate(kTextZ, sizeof(kTextZ), &out, 1000));
}

static void TestWire()
{
    net::Writer w;
    w.Varint(1, 1);
    w.Int32(2, -1);
    w.Varint(3, 300);
    w.Bytes(7, "N\0o\0", 4);
    w.Bytes(5, "\x10\x20", 2);
    w.Bytes(5, "\x00\x00", 2);
    w.Varint(9, 1);
    const std::string& d = w.Data();
    // -1 as an int32 is ten bytes of varint; 300 is ac 02.
    CHECK(d.size() == 2 + 11 + 3 + 6 + 4 + 4 + 2);
    CHECK((unsigned char)d[3] == 0xff && (unsigned char)d[12] == 0x01);
    CHECK((unsigned char)d[14] == 0xac && (unsigned char)d[15] == 0x02);
    net::Reader r;
    CHECK(r.Parse((const unsigned char*)d.data(), d.size()));
    CHECK(r.U32(1) == 1 && r.I32(2) == -1 && r.U32(3) == 300 && r.U64(9) == 1);
    CHECK(r.Has(7) && !r.Has(8) && r.Bytes(7) == std::string("N\0o\0", 4));
    CHECK(r.RepeatedBytes(5).size() == 2 && r.RepeatedBytes(5)[1] == std::string("\0\0", 2));
    CHECK(r.I32(6, 42) == 42); // absent: the default
    std::string packet = net::Pack(net::kSync, w);
    CHECK(packet[0] == 0 && packet[1] == net::kSync && packet.substr(2) == d);
    // Cut inside the name's bytes: its length runs past the end.
    CHECK(!r.Parse((const unsigned char*)d.data(), 19));
}

// EfzRevival's rand: std::minstd_rand through Visual C++ 2012's
// uniform_int_distribution(0, 0x7fff); the engine's values above 2^30 are drawn again.
static void TestRand()
{
    static const int seed1[8] = {15502, 22497, 16674, 28760, 26818, 19746, 29411, 21856};
    SetRevivalRand(true);
    SeedRevivalRand(1);
    for (int i = 0; i < 8; i++)
        CHECK(Rand() == seed1[i]);
    SeedRevivalRand(123456789);
    CHECK(Rand() == 1425 && Rand() == 24242 && Rand() == 26249 && Rand() == 13656);
    CHECK(RandState() == 291648857u);
    // A save state's restore.
    SetRevivalRandState(1);
    CHECK(Rand() == 15502);
    // std::minstd_rand's seeding: modulo 2^31 - 1, and 0 is 1.
    SeedRevivalRand(0);
    CHECK(RandState() == 1);
    SeedRevivalRand(2147483647u);
    CHECK(RandState() == 1);
    SeedRevivalRand(2147483648u);
    CHECK(RandState() == 1);
    // Off: the CRT's again, untouched by the other.
    SetRevivalRand(false);
    Srand(1);
    CHECK(Rand() == 41 && Rand() == 18467 && Rand() == 6334);
}

static void TestSockets()
{
    net::Endpoint e;
    std::string error;
    CHECK(net::Resolve("127.0.0.1:5", 10800, &e, &error) && e.Port() == 5 && !e.IsV6());
    CHECK(net::Resolve(" 127.0.0.1 ", 10800, &e, &error) && e.Port() == 10800);
    CHECK(e.ToString() == "127.0.0.1:10800");
    net::Endpoint v6;
    CHECK(net::Resolve("[::1]:7", 10800, &v6, &error) && v6.IsV6() && v6.Port() == 7);
    CHECK(v6.ToString() == "[::1]:7");
    net::Endpoint mapped;
    CHECK(net::Resolve("::ffff:127.0.0.1", 10800, &mapped, &error));
    CHECK(mapped.SameAddress(e) && !v6.SameAddress(e));
    CHECK(!net::Resolve("127.0.0.1:99999", 10800, &e, &error));
    CHECK(!net::Resolve("[::1", 10800, &e, &error));

    net::Socket a, b;
    CHECK(a.Open(4, 0, &error));
    CHECK(b.Open(0, 0, &error)); // IPv6 that takes IPv4 too, as a host's
    net::Endpoint toB;
    CHECK(net::Resolve("127.0.0.1", b.LocalPort(), &toB, &error));
    CHECK(a.SendTo("hello", 5, toB));
    CHECK(b.Wait(2000));
    char buffer[64];
    net::Endpoint from;
    int n = b.Receive(buffer, sizeof(buffer), &from);
    CHECK(n == 5 && memcmp(buffer, "hello", 5) == 0);
    CHECK(from.Port() == a.LocalPort());
    // And back, to the address the dual socket saw.
    CHECK(b.SendTo("ok", 2, from));
    CHECK(a.Wait(2000));
    n = a.Receive(buffer, sizeof(buffer), &from);
    CHECK(n == 2 && memcmp(buffer, "ok", 2) == 0);
    CHECK(a.Receive(buffer, sizeof(buffer), &from) == -1);
}

// The addresses a host shows: each an IPv4 address that can be joined, on a named adapter,
// none twice, none loopback or link-local. Which there are depends on the machine.
static void TestLocalAddresses()
{
    std::vector<net::LocalAddress> list = net::LocalAddresses();
    for (size_t i = 0; i < list.size(); i++) {
        printf("netplay: %s on %s\n", list[i].address.c_str(), list[i].network.c_str());
        net::Endpoint e;
        std::string error;
        CHECK(net::Resolve(list[i].address, 10800, &e, &error) && !e.IsV6());
        CHECK(list[i].address.compare(0, 4, "127.") != 0);
        CHECK(list[i].address.compare(0, 8, "169.254.") != 0);
        CHECK(!list[i].network.empty());
        for (size_t j = 0; j < i; j++)
            CHECK(list[j].address != list[i].address);
    }
}

int main()
{
    TestInflate();
    TestWire();
    TestRand();
    TestSockets();
    TestLocalAddresses();
    if (g_failed) {
        fprintf(stderr, "%d checks failed\n", g_failed);
        return 1;
    }
    printf("netplay: all checks pass\n");
    return 0;
}
